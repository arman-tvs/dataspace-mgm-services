"""Quality gate: the same checks for every author, person or coding agent (ADR-0003).

    uv run python tools/quality/gate.py                  # every area (CI)
    uv run python tools/quality/gate.py --changed        # areas with changes in the working tree
    uv run python tools/quality/gate.py FILE ...         # areas of these files (pre-commit)
    uv run python tools/quality/gate.py --hook           # Claude Code PostToolUse hook (JSON on stdin)
    uv run python tools/quality/gate.py --update-baseline  # lower the baseline after a cleanup

The checks are listed in `checks.py`. Existing findings are frozen per area and check in `baseline.json`
(a ratchet): the gate fails when a count goes up, so no change makes the code worse, and nobody has to
fix everything first. New areas start at zero. `--update-baseline` only lowers numbers.

Exit codes: 0 = no new findings, 1 = new findings, 2 = new findings in `--hook` mode (Claude Code shows
stderr to the agent, which then fixes them).
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from collections import Counter
from pathlib import Path, PurePosixPath

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from tools.quality import checks  # noqa: E402
from tools.quality.checks import Finding  # noqa: E402

BASELINE = Path(__file__).with_name("baseline.json")
SHOW = 30
Counts = dict[str, dict[str, int]]


def load_baseline() -> Counts:
    if not BASELINE.is_file():
        return {}
    data: Counts = json.loads(BASELINE.read_text(encoding="utf-8"))["areas"]
    return data


def save_baseline(counts: Counts) -> None:
    body = {"_comment": "Generated by tools/quality/gate.py. Existing findings per area and check; numbers may "
                        "only go down (--update-baseline). Never raise a number to make a change pass.",
            "limits": {"fileLines": checks.FILE_LINES, "functionLines": checks.FUNCTION_LINES},
            "areas": {area: dict(sorted(c.items())) for area, c in sorted(counts.items()) if any(c.values())}}
    BASELINE.write_text(json.dumps(body, indent=2) + "\n", encoding="utf-8")


def count(findings: list[Finding]) -> Counts:
    counts: Counts = {}
    for (area, check), n in Counter((f.area, f.check) for f in findings).items():
        counts.setdefault(area, {})[check] = n
    return counts


def compare(areas: list[str], now: Counts, base: Counts) -> tuple[list[tuple[str, str, int, int]], list[str]]:
    """(area, check, allowed, found) where a count went up; areas where a count went down."""
    worse, better = [], []
    for area in areas:
        found, allowed = now.get(area, {}), base.get(area, {})
        for check in sorted(set(found) | set(allowed)):
            n, limit = found.get(check, 0), allowed.get(check, 0)
            if n > limit:
                worse.append((area, check, limit, n))
            elif n < limit:
                better.append(f"{area} {check}: {limit} -> {n}")
    return worse, better


def report(worse: list[tuple[str, str, int, int]], findings: list[Finding], files: set[str]) -> str:
    lines = ["Quality gate: new findings (ADR-0003, tools/quality/gate.py).", ""]
    for area, check, allowed, found in worse:
        lines.append(f"{area} - {check}: {found} findings, baseline allows {allowed}")
        hits = [f for f in findings if f.area == area and f.check == check]
        mine = [f for f in hits if f.location.split(":")[0] in files] or hits
        lines += [f"  {f.location}: {f.message}" for f in mine[:SHOW]]
        if len(mine) > SHOW:
            lines.append(f"  ... {len(mine) - SHOW} more")
    lines += ["", "Fix the new findings. Do not raise numbers in tools/quality/baseline.json; if a rule is wrong "
              "for a case, say so in the pull request."]
    return "\n".join(lines)


def changed_files() -> list[str]:
    def git(*args: str) -> list[str]:
        out = subprocess.run(["git", *args], cwd=checks.ROOT, capture_output=True, text=True, check=False)
        return [line for line in out.stdout.splitlines() if line]
    return sorted(set(git("diff", "--name-only", "HEAD")) | set(git("ls-files", "--others", "--exclude-standard")))


def hook_files() -> list[str]:
    """The edited file of a Claude Code PostToolUse event (`tool_input.file_path`)."""
    try:
        event = json.load(sys.stdin)
    except ValueError:
        return []
    path = (event.get("tool_input") or {}).get("file_path") or ""
    try:
        return [Path(path).resolve().relative_to(checks.ROOT).as_posix()] if path else []
    except ValueError:
        return []           # outside the repository


def areas_for(files: list[str]) -> list[str]:
    return sorted({a for f in files if (a := checks.area_of(PurePosixPath(f))) is not None})


def run(areas: list[str], files: set[str], update: bool, hook: bool) -> int:
    findings = checks.collect(areas)
    now, base = count(findings), load_baseline()
    if update:
        lowered = {a: {c: min(n, now.get(a, {}).get(c, 0)) for c, n in checks_.items()} for a, checks_ in base.items()}
        save_baseline({**base, **{a: lowered[a] for a in areas if a in lowered}})
        print(f"Baseline lowered for {', '.join(areas)}.")
        return 0
    worse, better = compare(areas, now, base)
    if better:
        print("Improved (run with --update-baseline to lock it in):\n  " + "\n  ".join(better))
    if not worse:
        print(f"Quality gate passed: {len(areas)} area(s), no new findings.")
        return 0
    print(report(worse, findings, files), file=sys.stderr if hook else sys.stdout)
    return 2 if hook else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("files", nargs="*", help="check only the areas of these files")
    parser.add_argument("--changed", action="store_true", help="areas with changes in the working tree")
    parser.add_argument("--hook", action="store_true", help="Claude Code PostToolUse hook (JSON on stdin)")
    parser.add_argument("--update-baseline", action="store_true", help="lower the baseline to the current counts")
    parser.add_argument("--init-baseline", action="store_true", help="write the current counts (maintainers)")
    args = parser.parse_args(argv)
    files = hook_files() if args.hook else changed_files() if args.changed else list(args.files)
    areas = areas_for(files) if (args.hook or args.changed or args.files) else checks.all_areas()
    if not areas:
        return 0
    if args.init_baseline:
        save_baseline(count(checks.collect(areas)))
        print(f"Baseline written: {BASELINE.relative_to(checks.ROOT)}")
        return 0
    return run(areas, set(files), args.update_baseline, args.hook)


if __name__ == "__main__":
    sys.exit(main())
