"""Write the agent files of every tool from one source, so the copies cannot drift.

    uv run python tools/agents/build.py           # write the tool files
    uv run python tools/agents/build.py --check   # exit 1 if a tool file differs from its source (the gate)

Source, one folder per agent in `.agents/agents/<name>/`:

    instructions.md   the body, the same for every tool
    claude.yaml       frontmatter of the Claude Code agent      -> .claude/agents/<name>.md
    copilot.yaml      frontmatter of the GitHub Copilot agent   -> .github/agents/<name>.agent.md

Skills need no build: they live once in `.agents/skills/`, which most tools read, and `.claude/skills` is a link to
it. Agents need one, because every tool has its own frontmatter. A new tool gets one more entry in `TARGETS` and one
more `<tool>.yaml` per agent, never a copy of the instructions.
"""
from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / ".agents" / "agents"
TARGETS = {"claude": ".claude/agents/{name}.md", "copilot": ".github/agents/{name}.agent.md"}
NOTE = ("<!-- Generated by tools/agents/build.py from .agents/agents/{name}/ - edit there, then run the script.\n"
        "     dataspace-mgm-ui carries the same instructions; keep both repositories in sync. -->\n")


@dataclass(frozen=True, slots=True)
class AgentFile:
    path: Path
    text: str


def frontmatter(source: Path) -> str:
    """The YAML of `<tool>.yaml` without its leading comment block (license header and note)."""
    lines = source.read_text(encoding="utf-8").splitlines(keepends=True)
    start = next((i for i, line in enumerate(lines) if not line.startswith("#")), len(lines))
    return "".join(lines[start:])


def with_note(body: str, name: str) -> str:
    """The body with the generated-file note after its license comment (`-->`)."""
    marker = "-->\n"
    at = body.find(marker)
    cut = at + len(marker) if at >= 0 else 0
    return body[:cut] + "\n" + NOTE.format(name=name) + body[cut:]


def agent_files() -> list[AgentFile]:
    files = []
    for folder in sorted(p for p in SOURCE.iterdir() if p.is_dir()) if SOURCE.is_dir() else []:
        body = with_note((folder / "instructions.md").read_text(encoding="utf-8"), folder.name)
        for tool, pattern in TARGETS.items():
            header = folder / f"{tool}.yaml"
            if header.is_file():
                text = f"---\n{frontmatter(header)}---\n{body}"
                files.append(AgentFile(ROOT / pattern.format(name=folder.name), text))
    return files


def stale() -> list[str]:
    """Tool files that differ from their source, relative to the repository."""
    return [f.path.relative_to(ROOT).as_posix() for f in agent_files()
            if not f.path.is_file() or f.path.read_text(encoding="utf-8") != f.text]


def main(argv: list[str]) -> int:
    if "--check" in argv:
        out = stale()
        for path in out:
            print(f"{path} differs from .agents/agents/: edit the source there and run tools/agents/build.py")
        return 1 if out else 0
    for f in agent_files():
        f.path.parent.mkdir(parents=True, exist_ok=True)
        f.path.write_text(f.text, encoding="utf-8")
        print(f"wrote {f.path.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
