"""Agent files from one source (tools/agents/build.py): every tool's file is built, a hand edit is detected."""
from pathlib import Path

from tools.agents import build
from tools.quality import gate


def make_source(root: Path) -> None:
    folder = root / ".agents" / "agents" / "captain"
    folder.mkdir(parents=True)
    (folder / "instructions.md").write_text("<!--\n license\n-->\n\n# Captain\n", encoding="utf-8")
    (folder / "claude.yaml").write_text("# header\n# note\nname: captain\nmodel: opus\n", encoding="utf-8")
    (folder / "copilot.yaml").write_text("# header\nname: Captain\nicon: captain.png\n", encoding="utf-8")


def test_every_tool_file_is_built_from_the_one_source(tmp_path, monkeypatch):
    make_source(tmp_path)
    monkeypatch.setattr(build, "ROOT", tmp_path)
    monkeypatch.setattr(build, "SOURCE", tmp_path / ".agents" / "agents")
    assert build.main([]) == 0
    claude = (tmp_path / ".claude" / "agents" / "captain.md").read_text(encoding="utf-8")
    copilot = (tmp_path / ".github" / "agents" / "captain.agent.md").read_text(encoding="utf-8")
    assert claude.startswith("---\nname: captain\nmodel: opus\n---\n<!--\n license\n-->\n\n<!-- Generated by")
    assert copilot.startswith("---\nname: Captain\nicon: captain.png\n---\n")
    assert claude.endswith("# Captain\n") and copilot.endswith("# Captain\n")
    assert build.stale() == []


def test_a_hand_edit_of_one_copy_is_detected(tmp_path, monkeypatch):
    make_source(tmp_path)
    monkeypatch.setattr(build, "ROOT", tmp_path)
    monkeypatch.setattr(build, "SOURCE", tmp_path / ".agents" / "agents")
    build.main([])
    copy = tmp_path / ".github" / "agents" / "captain.agent.md"
    copy.write_text(copy.read_text(encoding="utf-8") + "edited by hand\n", encoding="utf-8")
    assert build.stale() == [".github/agents/captain.agent.md"]
    assert build.main(["--check"]) == 1


def test_the_repository_agent_files_match_their_source():
    assert build.stale() == []


def test_skills_have_one_source_and_claude_reads_them_through_a_link():
    root = build.ROOT
    link = root / ".claude" / "skills"
    assert link.is_symlink() and link.resolve() == (root / ".agents" / "skills").resolve()
    assert (root / ".agents" / "skills" / "review-module" / "SKILL.md").is_file()


def test_the_gate_checks_the_agent_files():
    assert gate.areas_for([".claude/agents/dataspace-captain.md", ".agents/agents/x/instructions.md"]) == ["agents"]
